const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("neoBrowser", {
  createTab: (url, options) => ipcRenderer.invoke("tabs:create", url, options),
  duplicateTab: (id) => ipcRenderer.invoke("tabs:duplicate", id),
  togglePinTab: (id) => ipcRenderer.invoke("tabs:toggle-pin", id),
  clearBrowserData: () => ipcRenderer.invoke("browser:clear-data"),
  openRiskPage: (url) => ipcRenderer.invoke("browser:open-risk-page", url),
  getDownloadHistory: () => ipcRenderer.invoke("downloads:get"),
  openDownloadedFile: (id) => ipcRenderer.invoke("downloads:open", id),
  showDownloadedFile: (id) => ipcRenderer.invoke("downloads:show-in-folder", id),
  clearDownloadHistory: () => ipcRenderer.invoke("downloads:clear-history"),
  onDownloadsChanged: (callback) => { ipcRenderer.removeAllListeners("downloads:state"); ipcRenderer.on("downloads:state", (_event, list) => callback(list)); },
  hasPasswordManagerPin: () => ipcRenderer.invoke("passwords:has-pin"),
  setPasswordManagerPin: (pin) => ipcRenderer.invoke("passwords:set-pin", pin),
  getSavedPasswords: (pin) => ipcRenderer.invoke("passwords:get", pin),
  deleteSavedPassword: (pin, id) => ipcRenderer.invoke("passwords:delete", pin, id),
  copySavedPassword: (pin, id) => ipcRenderer.invoke("passwords:copy", pin, id),
  openPasswordSite: (url) => ipcRenderer.invoke("passwords:open-url", url),
  onPasswordsChanged: (callback) => { ipcRenderer.removeAllListeners("passwords:changed"); ipcRenderer.on("passwords:changed", () => callback()); },
  onOpenPasswordSettings: (callback) => { ipcRenderer.removeAllListeners("passwords:open-settings"); ipcRenderer.on("passwords:open-settings", () => callback()); },
  getSitePermissionsForActiveSite: () => ipcRenderer.invoke("browser:get-site-permissions"),
  getSiteSecurityForActiveSite: () => ipcRenderer.invoke("browser:get-site-security"),
  getAdBlockStats: () => ipcRenderer.invoke("browser:get-adblock-stats"),
  onAdBlockState: (callback) => { ipcRenderer.removeAllListeners("adblock:state"); ipcRenderer.on("adblock:state", (_event, stats) => callback(stats)); },
  onAdBlockCount: (callback) => { ipcRenderer.removeAllListeners("adblock:count"); ipcRenderer.on("adblock:count", (_event, stats) => callback(stats)); },
  setSitePermissionsForActiveSite: (values) => ipcRenderer.invoke("browser:set-site-permissions", values),
  installUpdate: () => ipcRenderer.invoke("updater:install"),
  getBlockedNotificationOrigins: () => ipcRenderer.invoke("browser:blocked-notifications:get"),
  unblockNotificationOrigin: (origin) => ipcRenderer.invoke("browser:blocked-notifications:unblock", origin),
  onBlockedNotificationsChanged: (callback) => { ipcRenderer.removeAllListeners("browser:blocked-notifications-changed"); ipcRenderer.on("browser:blocked-notifications-changed", () => callback()); },
  closeActiveTab: () => ipcRenderer.send("browser:close-active-tab"),
  openNeoAI: () => ipcRenderer.invoke("sidebar:open-neoai"),
  openNeoAIWithPrompt: (text) => ipcRenderer.invoke("sidebar:open-neoai-prompt", text),
  onContextSearchSelection: (callback) => { ipcRenderer.removeAllListeners("context:search-selection"); ipcRenderer.on("context:search-selection", (_event, text) => callback(text)); },
  onContextAskNeoAI: (callback) => { ipcRenderer.removeAllListeners("context:ask-neoai"); ipcRenderer.on("context:ask-neoai", (_event, text) => callback(text)); },
  switchTab: (id) => ipcRenderer.send("tabs:switch", id),
  closeTab: (id) => ipcRenderer.send("tabs:close", id),
  reorderTabs: (fromId, toId) => ipcRenderer.send("tabs:reorder", fromId, toId),
  navigate: (url) => ipcRenderer.send("tabs:navigate", url),
  back: () => ipcRenderer.send("browser:back"),
  forward: () => ipcRenderer.send("browser:forward"),
  reload: () => ipcRenderer.send("browser:reload"),
  home: () => ipcRenderer.send("browser:home"),
  setBounds: (bounds) => ipcRenderer.send("browser:set-bounds", bounds),
  hideContent: () => ipcRenderer.send("browser:hide-content"),
  showContent: () => ipcRenderer.send("browser:show-content"),
  openDefaultApps: () => ipcRenderer.invoke("browser:open-default-apps"),
  chooseBookmarksFile: () => ipcRenderer.invoke("import:choose-bookmarks"),
  chooseSourceProfile: (sourceBrowser) => ipcRenderer.invoke("import:choose-source-profile", sourceBrowser),
  importSourceProfile: (sourceBrowser, profilePath, selected) => ipcRenderer.invoke("import:source-profile", sourceBrowser, profilePath, selected),
  setBrowserLanguage: (language) => ipcRenderer.invoke("browser:set-language", language),
  checkForUpdates: () => ipcRenderer.invoke("updater:check"),
  getVersion: () => ipcRenderer.invoke("updater:version"),
  openDevTools: () => ipcRenderer.invoke("browser:open-devtools"),
  onUpdaterState: (callback) => {
    ipcRenderer.removeAllListeners("updater:state");
    ipcRenderer.on("updater:state", (_event, state) => callback(state));
  },
  onFocusAddress: (callback) => { ipcRenderer.removeAllListeners("browser:focus-address"); ipcRenderer.on("browser:focus-address", () => callback()); },
  onShortcut: (callback) => { ipcRenderer.removeAllListeners("browser:shortcut"); ipcRenderer.on("browser:shortcut", (_event, action) => callback(action)); },
  onTabsState: (callback) => {
    ipcRenderer.removeAllListeners("tabs:state");
    ipcRenderer.on("tabs:state", (_event, state) => callback(state));
  }
});
